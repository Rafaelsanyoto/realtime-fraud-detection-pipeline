import json
import random
import time
import uuid
from datetime import datetime
from pathlib import Path
import os
from dotenv import load_dotenv
import pandas as pd
import psycopg2
from confluent_kafka import Producer

BASE_DIR = Path(__file__).resolve().parent

load_dotenv(BASE_DIR / ".env")

DB_CONFIG = {
    "host": os.getenv("POSTGRES_HOST", "localhost"),
    "dbname": os.getenv("POSTGRES_DB", "fraud_detection"),
    "user": os.getenv("POSTGRES_USER", "postgres"),
    "password": os.getenv("POSTGRES_PASSWORD"),
    "port": int(os.getenv("POSTGRES_PORT", "5432"))
}

KAFKA_BOOTSTRAP_SERVERS = os.getenv("KAFKA_BOOTSTRAP_SERVERS")

if not KAFKA_BOOTSTRAP_SERVERS:
    raise ValueError("KAFKA_BOOTSTRAP_SERVERS is missing from .env")

DATASET_PATH = BASE_DIR / "bs140513_032310.csv"
TOPIC_NAME = "banksim_transactions"
STREAM_LIMIT = 10000
BATCH_MIN = 5
BATCH_MAX = 10
WAIT_MIN = 5
WAIT_MAX = 10

producer = Producer({"bootstrap.servers": KAFKA_BOOTSTRAP_SERVERS})

def delivery_report(err, msg):
    if err is not None:
        print(f"Message delivery failed: {err}")

def get_historical_ids():
    conn = psycopg2.connect(**DB_CONFIG)
    cur = conn.cursor()

    cur.execute("SELECT transaction_id FROM transactions")
    historical_ids = {row[0] for row in cur.fetchall()}

    cur.close()
    conn.close()

    return historical_ids

def main():
    if not DATASET_PATH.exists():
        raise FileNotFoundError(f"Dataset not found: {DATASET_PATH}")

    print("Loading BankSim dataset...")
    df = pd.read_csv(DATASET_PATH)

    # Use the same IDs generated by main.py to identify previously loaded records
    df["source_transaction_id"] = [
        f"BS{index + 1:08d}" for index in df.index
    ]

    historical_ids = get_historical_ids()

    # Avoid sending the historical sample through Kafka a second time
    stream_df = df[
        ~df["source_transaction_id"].isin(historical_ids)
    ]

    if len(stream_df) < STREAM_LIMIT:
        raise ValueError("Not enough transactions available for streaming.")

    stream_df = stream_df.sample(
        n=STREAM_LIMIT,
        random_state=42
    ).reset_index(drop=True)

    records = stream_df.to_dict(orient="records")
    random.shuffle(records)

    print(f"Historical records excluded: {len(historical_ids)}")
    print(f"Streaming pool: {len(records)} transactions")

    current_idx = 0
    cycle = 1
    total_published = 0

    try:
        while True:
            if current_idx >= len(records):
                current_idx = 0
                cycle += 1
                random.shuffle(records)
                print(f"Starting streaming replay cycle {cycle}")

            # Vary the batch sizes and delays to simulate uneven transaction arrivals
            batch_size = random.randint(BATCH_MIN, BATCH_MAX)
            sleep_time = random.randint(WAIT_MIN, WAIT_MAX)
            batch = records[current_idx:current_idx + batch_size]

            for row in batch:
                transaction_data = {
                    "transaction_id": f"LIVE-{uuid.uuid4().hex}",
                    "customer_id": str(row["customer"]),
                    "merchant_id": str(row["merchant"]),
                    "category": str(row["category"]),
                    "amount": float(row["amount"]),
                    "transaction_time": datetime.now().isoformat(timespec="seconds"),
                    "step": int(row["step"])
                }

                producer.produce(
                    TOPIC_NAME,
                    key=transaction_data["customer_id"],
                    value=json.dumps(transaction_data),
                    on_delivery=delivery_report
                )

                producer.poll(0)

            remaining = producer.flush(30)

            if remaining:
                print(f"{remaining} messages were not delivered.")

            current_idx += len(batch)
            total_published += len(batch)

            print(
                f"Cycle {cycle} | "
                f"Published this batch: {len(batch)} | "
                f"Total published: {total_published} | "
                f"Next batch in {sleep_time} seconds"
            )

            time.sleep(sleep_time)

    except KeyboardInterrupt:
        print("Transaction producer stopped.")

    finally:
        producer.flush(30)

if __name__ == "__main__":
    main()
